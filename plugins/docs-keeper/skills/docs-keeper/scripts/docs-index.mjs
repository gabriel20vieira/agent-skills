#!/usr/bin/env node
// Keeps the docs index in CLAUDE.md in sync with docs/**/*.md.
//
//   node docs-index.mjs index   write the index block into CLAUDE.md (creates it if missing)
//   node docs-index.mjs check   exit 1 if the block is not what index would write
//   node docs-index.mjs stale   list docs whose Sources changed after their Updated date
//
// Runs in the repo of the current folder. A doc is `# Title`, then `> one-line summary`, then
// `Updated: yyyy-mm-dd` and `Sources: path, path`. The index lists every doc by its first
// folder under docs/ (its category), between the START and END markers.
import { execFileSync } from "node:child_process"
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { basename, join, relative, resolve, sep } from "node:path"
import { fileURLToPath } from "node:url"

export const START = "<!-- docs-index:start -->"
export const END = "<!-- docs-index:end -->"
const NOTE = "_Generated by docs-keeper (`docs-index.mjs index`); do not edit by hand._"

/** Title, summary (a quote right after the title), Updated date and Sources of one doc. */
export function parseDoc(text) {
    const lines = text.replace(/\r\n/g, "\n").split("\n")
    let at = lines.findIndex((line) => line.trim() !== "")
    const titleMatch = at >= 0 ? lines[at].match(/^#\s+(.+?)\s*$/) : null
    const title = titleMatch ? titleMatch[1] : ""
    let summary = ""
    if (titleMatch) {
        at += 1
        while (at < lines.length && lines[at].trim() === "") at += 1
        const quote = at < lines.length ? lines[at].match(/^>\s?(.*)$/) : null
        if (quote) summary = quote[1].trim()
    }
    const field = (name) => {
        const line = lines.find((candidate) => candidate.startsWith(`${name}:`))
        return line ? line.slice(name.length + 1).trim() : ""
    }
    const sources = field("Sources").split(",").map((item) => item.trim()).filter(Boolean)
    return { title, summary, updated: field("Updated"), sources }
}

function listMarkdown(dir) {
    const out = []
    if (!existsSync(dir)) return out
    for (const entry of readdirSync(dir)) {
        if (entry.startsWith(".") || entry === "node_modules") continue
        const path = join(dir, entry)
        if (statSync(path).isDirectory()) out.push(...listMarkdown(path))
        else if (entry.endsWith(".md")) out.push(path)
    }
    return out
}

/** Every doc under <root>/docs with its category (first folder, "" for docs/ itself). */
export function collectDocs(root) {
    const docsDir = join(root, "docs")
    const docs = listMarkdown(docsDir).map((file) => {
        const path = relative(root, file).split(sep).join("/")
        const parts = relative(docsDir, file).split(sep)
        const parsed = parseDoc(readFileSync(file, "utf8"))
        return { path, category: parts.length > 1 ? parts[0] : "", ...parsed, title: parsed.title || basename(file, ".md") }
    })
    return docs.sort((a, b) => (a.category === b.category ? a.path.localeCompare(b.path) : a.category.localeCompare(b.category)))
}

/** The index block, markers included. */
export function renderIndex(docs) {
    const sections = []
    let current = null
    for (const doc of docs) {
        if (doc.category !== current) {
            current = doc.category
            sections.push(`\n### ${current || "docs"}`)
        }
        sections.push(`- [${doc.title}](${doc.path})${doc.summary ? ` - ${doc.summary}` : ""}`)
    }
    return [START, NOTE, ...sections, END].join("\n")
}

/** CLAUDE.md text with the block replaced, appended in a Docs section, or a new file. */
export function applyIndex(text, block, projectName) {
    if (text === null) return `# ${projectName}\n\n## Docs\n\n${block}\n`
    const crlf = text.includes("\r\n")
    const plain = text.replace(/\r\n/g, "\n")
    const start = plain.indexOf(START)
    const end = plain.indexOf(END)
    const next = start >= 0 && end > start
        ? plain.slice(0, start) + block + plain.slice(end + END.length)
        : `${plain.trimEnd()}\n\n## Docs\n\n${block}\n`
    return crlf ? next.replace(/\n/g, "\r\n") : next
}

function readClaude(root) {
    const path = join(root, "CLAUDE.md")
    return { path, text: existsSync(path) ? readFileSync(path, "utf8") : null }
}

export function writeIndex(root) {
    const { path, text } = readClaude(root)
    const next = applyIndex(text, renderIndex(collectDocs(root)), basename(resolve(root)))
    if (next === text) return { changed: false, path }
    writeFileSync(path, next)
    return { changed: true, path }
}

export function checkIndex(root) {
    const { text } = readClaude(root)
    const expected = collectDocs(root).map((doc) => doc.path)
    const plain = (text ?? "").replace(/\r\n/g, "\n")
    const start = plain.indexOf(START)
    const end = plain.indexOf(END)
    const current = start >= 0 && end > start ? plain.slice(start, end + END.length) : ""
    const listed = [...current.matchAll(/\]\((docs\/[^)]+)\)/g)].map((match) => match[1])
    const missing = expected.filter((path) => !listed.includes(path))
    const extra = listed.filter((path) => !expected.includes(path))
    return { ok: current === renderIndex(collectDocs(root)), missing, extra }
}

/** Docs with a source whose last commit is newer than the doc's Updated date. */
export function findStale(root) {
    const stale = []
    for (const doc of collectDocs(root)) {
        if (!doc.updated || doc.sources.length === 0) continue
        for (const source of doc.sources) {
            const changed = execFileSync("git", ["log", "-1", "--format=%cs", "--", source], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim()
            if (changed && changed > doc.updated) {
                stale.push({ path: doc.path, updated: doc.updated, source, changed })
                break
            }
        }
    }
    return stale
}

function main(argv) {
    const usage = "Usage: docs-index.mjs index | check | stale"
    const root = (() => {
        try { return execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() }
        catch { return process.cwd() }
    })()
    const [command] = argv
    if (command === "index") {
        const result = writeIndex(root)
        console.log(result.changed ? `Updated ${result.path}` : `${result.path} already up to date`)
        return 0
    }
    if (command === "check") {
        const result = checkIndex(root)
        if (result.ok) {
            console.log("Docs index is up to date")
            return 0
        }
        for (const path of result.missing) console.log(`missing: ${path}`)
        for (const path of result.extra) console.log(`listed but gone: ${path}`)
        if (result.missing.length === 0 && result.extra.length === 0) console.log("titles or summaries changed")
        console.log("Run: node docs-index.mjs index")
        return 1
    }
    if (command === "stale") {
        const stale = findStale(root)
        for (const item of stale) console.log(`${item.path}: ${item.source} changed ${item.changed}, doc updated ${item.updated}`)
        if (stale.length === 0) console.log("No stale docs")
        return 0
    }
    console.error(usage)
    return 2
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        process.exitCode = main(process.argv.slice(2))
    } catch (error) {
        console.error(error.message)
        process.exitCode = 1
    }
}
